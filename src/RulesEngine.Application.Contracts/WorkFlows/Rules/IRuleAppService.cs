using RulesEngine.WorkFlows.Dtos;
using RulesEngine.WorkFlows.Dtos.RulesDtos;
using RulesEngine.WorkFlows.Rules.RuleExpressionBuilders;
using System;
using System.Collections.Generic;
using System.Data;
using System.Text;
using System.Threading.Tasks;
using Volo.Abp.Application.Dtos;
using Volo.Abp.Application.Services;
using Volo.Abp.Content;

namespace RulesEngine.WorkFlows.Rules
{
    public interface IRuleAppService : ICrudAppService< RuleDto, RuleListItemDto, Guid, RulePagedAndSortedResultRequestDto, CreateRuleDto, CreateRuleDto>
    {
        Task<RuleExpressionResultDto> PreviewExpression(RuleDto input);
        /// <summary>
        /// Generates a CSV sample for creating rules for the given workflow. Columns are derived from the workflow's RuleFormConfig. If the workflow has existing rules, they will be included as rows.
        /// Returns the CSV content as UTF8 bytes.
        /// </summary>
        Task<IRemoteStreamContent> GetRulesSampleAsync(Guid workflowId);

        /// <summary>
        /// Bulk uploads rules for the given workflow. The fileContent should be a CSV (UTF8) matching the sample generated by GetRulesSampleAsync.
        /// Each row will create one rule using equality conditions for provided fields.
        /// </summary>
        Task<IRemoteStreamContent?> BulkUploadAsync(Guid workflowId, IRemoteStreamContent fileContent);
    }
}
